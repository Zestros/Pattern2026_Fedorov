class conversion_context_dto:
    """Хранит ссылки и путь полей одной операции сериализации графа."""

    def __init__(self) -> None:
        """Создаёт независимый реестр объектов для одной выгрузки."""
        # Идентичность исходного объекта - служебный ID в JSON.
        self.object_ids: dict[int, str] = {}
        # Удерживает объекты, чтобы Python не переиспользовал их id во время обхода.
        self.objects: dict[int, object] = {}
        # Имена полей текущей ветки для сообщения об ошибке.
        self.path: list[str] = []
