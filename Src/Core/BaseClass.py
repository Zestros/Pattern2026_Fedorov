"""Базовый класс объектов с уникальным идентификатором и именем."""

from abc import ABC
import uuid


class base_class(ABC):
    """Хранит идентификатор объекта и изменяемое имя.

    Идентификатор создаётся один раз и доступен только для чтения.
    Имя изначально пустое и задаётся методом set_name.
    """

    def __init__(self) -> None:
        """Создаёт идентификатор UUID4 и задаёт пустое начальное имя."""
        # Уникальный идентификатор текущего объекта.
        self.__id = uuid.uuid4()
        # Имя объекта до первого вызова set_name остаётся пустым.
        self.__name = ""

    @property
    def get_id(self) -> uuid.UUID:
        """Возвращает доступный только для чтения идентификатор объекта."""
        return self.__id

    @property
    def get_name(self):
        """Возвращает текущее имя объекта, изначально пустое."""
        return self.__name

    def set_name(self, name) -> None:
        """Устанавливает имя объекта.

        Args:
            name: Новое имя объекта. Ожидается непустая строка.

        Raises:
            ValueError: Если значение name ложно при проверке bool(name).

        Тип значения и наличие пробелов отдельно не проверяются.
        """
        if not name:
            raise ValueError("Имя не может быть пустым")
        self.__name = name
